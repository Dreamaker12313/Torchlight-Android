#!/usr/bin/env python3
"""Derive the Switch NRO's icon, and the iOS app's, from `src/logo.jpg`.

The `.nro` carries its icon as a **256x256 JPEG** in the asset section, and that
size is not advisory: libnx's own `default_icon.jpg` is exactly 256x256, and the
home-brew menu decodes into a slot of that size. `src/logo.jpg` is the artwork at
1024x1024, which is the right thing to keep in the repository and the wrong thing
to hand to `elf2nro`.

This would ideally run at build time, but it cannot: devkitPro's MSYS2 shell -
the only shell the Switch target configures in - has no Python at all, let alone
Pillow. So the derived icon is committed beside the source and regenerated by
hand when the artwork changes. The iOS app's icon (`--ios`) is the artwork at
1024x1024 as an RGB PNG, the one size Xcode's asset catalogue asks for (an App
Store icon has no alpha), and is committed the same way:

    python scripts/make_icon.py
    python scripts/make_icon.py --ios

Reads and writes only this repository's own files; no game content is involved.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

# What the NRO asset section and the home-brew menu expect.
ICON_SIZE = 256

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "src" / "logo.jpg"
DEFAULT_OUTPUT = ROOT / "src" / "logo_icon.jpg"
IOS_ICON_SIZE = 1024
IOS_OUTPUT = ROOT / "src" / "platform" / "ios" / "Assets.xcassets" / "AppIcon.appiconset" / "AppIcon.png"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=pathlib.Path, default=DEFAULT_SOURCE,
                        help="the artwork to derive from (default: src/logo.jpg)")
    parser.add_argument("--output", type=pathlib.Path, default=DEFAULT_OUTPUT,
                        help="where to write the icon (default: src/logo_icon.jpg)")
    parser.add_argument("--quality", type=int, default=92,
                        help="JPEG quality (default: 92)")
    parser.add_argument("--ios", action="store_true",
                        help=f"write the iOS app icon instead ({IOS_OUTPUT.relative_to(ROOT).as_posix()})")
    args = parser.parse_args(argv)

    try:
        from PIL import Image
    except ImportError:
        print("needs pillow: pip install pillow", file=sys.stderr)
        return 1

    if not args.source.is_file():
        print(f"no artwork at {args.source}", file=sys.stderr)
        return 1

    size = IOS_ICON_SIZE if args.ios else ICON_SIZE
    output = IOS_OUTPUT if args.ios else args.output
    with Image.open(args.source) as image:
        # RGB because the NRO icon is a baseline JPEG; an alpha channel or a
        # palette would not survive the encode in any useful way.
        icon = image.convert("RGB").resize((size, size), Image.LANCZOS)
        if args.ios:
            icon.save(output, "PNG", optimize=True)
        else:
            icon.save(output, "JPEG", quality=args.quality, optimize=True)

    print(f"{args.source.name} ({image.size[0]}x{image.size[1]}) -> "
          f"{output.name} ({size}x{size}, {output.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
